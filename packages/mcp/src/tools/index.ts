export function registerAllTools(server: McpServer, config: MCPConfig): void {
  registerSendEmail(server, config);
  registerListRecentSends(server, config);
  registerGetEmailEventLog(server, config);
  registerVerifyDomainStatus(server, config);
  registerListSuppressions(server, config);
  registerGetSetupStatus(server, config);
  // Pricing needs no AWS access — always available.
  registerEstimateCost(server);
  if (config.api) {
    // API-backed tools (registered only with Wraps credentials).
    registerListContacts(server, config);
    registerGetContact(server, config);
    registerCreateContact(server, config);
    registerUpdateContact(server, config);
    registerSetContactTopics(server, config);
    registerDeleteContact(server, config);
    registerValidateContactEmails(server, config);
    registerImportContacts(server, config);
    registerExportContacts(server, config);
    registerListSegments(server, config);
    registerGetSegment(server, config);
    registerPreviewSegment(server, config);
    registerCreateSegment(server, config);
    registerUpdateSegment(server, config);
    registerDeleteSegment(server, config);
    registerListTopics(server, config);
    registerGetTopic(server, config);
    registerListTopicSubscribers(server, config);
    registerCreateTopic(server, config);
    registerUpdateTopic(server, config);
    registerDeleteTopic(server, config);
    registerListTemplates(server, config);
    registerGetTemplate(server, config);
    registerCreateTemplate(server, config);
    registerUpdateTemplate(server, config);
    registerDuplicateTemplate(server, config);
    registerPublishTemplate(server, config);
    registerDeleteTemplate(server, config);
    registerListBroadcasts(server, config);
    registerGetBroadcast(server, config);
    registerListBroadcastRecipients(server, config);
    registerGetBroadcastClicks(server, config);
    registerCreateBroadcast(server, config);
    registerUpdateBroadcast(server, config);
    registerDuplicateBroadcast(server, config);
    registerSendBroadcast(server, config);
    registerResumeBroadcast(server, config);
    registerCancelBroadcast(server, config);
    registerListEvents(server, config);
    registerGetEvent(server, config);
    registerGetEventAnalytics(server, config);
    registerListEventNames(server, config);
    registerTrackEvent(server, config);
    registerRemoveSuppression(server, config);
    registerAddSuppression(server, config);
    registerListWorkflows(server, config);
    registerGetWorkflow(server, config);
    registerListWorkflowExecutions(server, config);
    registerGetWorkflowExecution(server, config);
    registerEnableWorkflowSchedule(server, config);
    registerDisableWorkflowSchedule(server, config);
    registerTriggerWorkflow(server, config);
    registerRetryWorkflowExecution(server, config);
    registerCancelWorkflowExecution(server, config);
    registerListAgentApprovals(server, config);
    registerListAgents(server, config);
    if (!config.enforcedMode) {
      registerApproveAgentApproval(server, config);
    }
    if (!config.enforcedMode) {
      registerRejectAgentApproval(server, config);
    }
    if (!config.enforcedMode) {
      registerCreateAgent(server, config);
      registerKillAgent(server, config);
      registerSetAgentPolicy(server, config);
    }
    registerGetEmailMetrics(server, config);
    registerListInboundEmails(server, config);
    registerGetInboundEmail(server, config);
    registerListBrandKits(server, config);
    registerGetBrandKit(server, config);
    registerCreateBrandKit(server, config);
    registerUpdateBrandKit(server, config);
    registerSetDefaultBrandKit(server, config);
    registerDeleteBrandKit(server, config);
    registerGetAccountHealth(server, config);
    registerEmailCheck(server, config);
  }
  if (config.enforcedMode) {
    registerCheckSendStatus(server, config);
  }
}
